"""
Сумма введённых чисел до нуля. Программа вводит числа (int(input(...))) до тех пор, пока пользователь не введёт 0,
а затем выводит сумму всех введённых чисел. Использовать while и break. Подсказка: накапливайте сумму в переменной, а
0 — сигнал остановки.
"""
summ = 0

while True:
    num = int(input("Число: "))
    if num == 0:
        break
    summ += num

print("Сумма всех чисел:", summ)
